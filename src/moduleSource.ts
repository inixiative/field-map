import type { FieldMap } from './types';

/** `exportName`: the map's const (default `fieldMap`); its type is the same name, capitalized.
 *  `extraExports`: more consts written beside it, by name (`unsupportedColumns`). `header`: the
 *  comment line that says how to regenerate. */
export type FieldMapModuleOptions = {
  exportName?: string;
  extraExports?: Record<string, unknown>;
  header?: string;
};

const IDENTIFIER = /^[A-Za-z_$][\w$]*$/;

const identifier = (name: string): string => {
  if (!IDENTIFIER.test(name))
    throw new Error(`fieldMapModuleSource: '${name}' is not an identifier`);
  return name;
};

/**
 * The text of a TypeScript module that holds a field map with its literal types:
 * `export const <name> = {...} as const satisfies FieldMap;` and `export type <Name> = typeof
 * <name>;`, then each extra export as a readonly const. Written as given, so a map read in the
 * same order gives the same text: no change to the schema, no diff.
 */
export const fieldMapModuleSource = (
  map: FieldMap,
  options: FieldMapModuleOptions = {},
): string => {
  const name = identifier(options.exportName ?? 'fieldMap');
  const typeName = identifier(name[0].toUpperCase() + name.slice(1));
  const header = options.header ?? '// Generated by @inixiative/field-map. Do not edit.';
  const extras = Object.entries(options.extraExports ?? {}).map(
    ([extra, value]) =>
      `\nexport const ${identifier(extra)} = ${JSON.stringify(value, null, 2)} as const;\n`,
  );
  return [
    `${header}\nimport type { FieldMap } from '@inixiative/field-map';\n`,
    `\nexport const ${name} = ${JSON.stringify(map, null, 2)} as const satisfies FieldMap;\n`,
    `\nexport type ${typeName} = typeof ${name};\n`,
    ...extras,
  ].join('');
};
