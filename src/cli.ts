#!/usr/bin/env node
import { existsSync, mkdirSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { parseArgs } from 'node:util';
import { fieldMapModuleSource } from './moduleSource';
import { readPrismaClientV6 } from './prisma/v6/build';
import { readPrismaClientV7 } from './prisma/v7/build';

const USAGE = `field-map generate --client <dir> --out <file> [--layout v6|v7] [--export <name>]

Reads a generated Prisma client and writes a module holding its field map with literal types:
  export const <name> = {...} as const satisfies FieldMap;   (default name: prismaMap)
  export type <Name> = typeof <name>;
  export const unsupportedColumns = {...} as const;           (Unsupported(...) columns per model)
--layout is detected from the client directory when omitted (v7 has internal/class.ts).`;

const fail = (message: string): never => {
  console.error(`${message}\n\n${USAGE}`);
  process.exit(1);
};

const [command, ...rest] = process.argv.slice(2);
if (command !== 'generate') fail(command ? `unknown command '${command}'` : 'no command');

const { values } = parseArgs({
  args: rest,
  options: {
    client: { type: 'string' },
    out: { type: 'string' },
    layout: { type: 'string' },
    export: { type: 'string' },
  },
});
const client = values.client ? resolve(values.client) : fail('--client is required');
const out = values.out ? resolve(values.out) : fail('--out is required');
const layout = values.layout ?? (existsSync(join(client, 'internal', 'class.ts')) ? 'v7' : 'v6');
if (layout !== 'v6' && layout !== 'v7') fail(`--layout must be v6 or v7, not '${layout}'`);

const { map, unsupportedColumns } =
  layout === 'v7' ? readPrismaClientV7(client) : readPrismaClientV6(client);
mkdirSync(dirname(out), { recursive: true });
writeFileSync(
  out,
  fieldMapModuleSource(map, {
    exportName: values.export ?? 'prismaMap',
    extraExports: { unsupportedColumns },
    header: '// Generated by `field-map generate` (@inixiative/field-map). Do not edit.',
  }),
);
console.log(
  `field map written to ${out} (${Object.keys(map.models).length} models, ${Object.keys(map.enums ?? {}).length} enums)`,
);
